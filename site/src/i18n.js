let lang = localStorage.getItem("andensur-lang") === "en" ? "en" : "es";

export function getLang() {
  return lang;
}

export function t(key, vars = {}) {
  const bag = STR[lang] || STR.es;
  let text = bag[key] ?? STR.es[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function applyI18n() {
  document.documentElement.lang = lang;
  document.title = t("docTitle");
  for (const el of document.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
  const button = document.getElementById("lang");
  if (button) {
    button.textContent = lang === "es" ? "English" : "Español";
    button.setAttribute("lang", lang === "es" ? "en" : "es");
  }
}

export function toggleLang() {
  lang = lang === "es" ? "en" : "es";
  localStorage.setItem("andensur-lang", lang);
  applyI18n();
  return lang;
}
